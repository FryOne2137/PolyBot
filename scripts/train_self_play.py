"""Stage 2: improve an existing belief model with in-memory MCTS self-play."""

from __future__ import annotations

import argparse
from pathlib import Path

from _bootstrap import add_local_source_root

add_local_source_root()

from polybot.infrastructure.device import select_device
from polybot.infrastructure.model_io import load_model
from polybot.training.cli import (
    add_environment_options,
    mcts_config_from_args,
    print_summary,
    training_config_from_args,
)
from polybot.training.self_play_train import train_self_play


def main() -> None:
    parser = argparse.ArgumentParser(description="Run RAM-only MCTS self-play; save only model weights")
    add_environment_options(parser)
    parser.add_argument("--model-in", type=Path, required=True)
    parser.add_argument("--model-out", type=Path, default=Path("models/self_play.pt"))
    parser.add_argument("--games", type=int, default=200)
    parser.add_argument("--updates-per-game", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--exploration-rate", type=float, default=0.20)
    parser.add_argument("--priority-replay-fraction", type=float, default=0.35)
    parser.add_argument("--td-lambda", type=float, default=1.0, help="1.0 propagates the exact final result through the full game.")
    parser.add_argument(
        "--teacher-policy-target-weight", type=float, default=0.10,
        help="Blend this fraction of the legal-action teacher into each MCTS policy target.",
    )
    parser.add_argument("--opponent", choices=["self_play", "random", "heuristic", "model", "mixed"], default="self_play")
    parser.add_argument("--random-opponent-rate", type=float, default=0.50)
    parser.add_argument("--mixed-opponent", choices=["random", "heuristic", "model"], default="heuristic")
    parser.add_argument(
        "--opponent-model",
        type=Path,
        action="append",
        default=[],
        help="Frozen checkpoint for --opponent model / --mixed-opponent model; repeat to sample a pool.",
    )
    parser.add_argument(
        "--teacher-replay-fraction",
        type=float,
        default=0.25,
        help="Fraction of every optimisation batch regenerated by the heuristic teacher in RAM.",
    )
    parser.add_argument("--simulations", type=int, default=64)
    parser.add_argument("--particles", type=int, default=4)
    parser.add_argument("--inference-batch-size", type=int, default=32)
    parser.add_argument("--mcts-threads", type=int, help="C++ threads used by PolyEnv MctsPool; default uses logical cores")
    parser.add_argument("--mcts-max-actions", type=int, default=1024)
    parser.add_argument("--strategic-prior-weight", type=float, default=1.0)
    parser.add_argument(
        "--teacher-prior-weight", type=float, default=0.20,
        help="Legal-action teacher anchor inside MCTS priors; use 0.0 for pure network search.",
    )
    parser.add_argument(
        "--workers", type=int, default=32,
        help="Number of active games in one global native MctsPool (legacy fallback: Python actors).",
    )
    parser.add_argument(
        "--global-inference-batch-size", type=int, default=256,
        help="Maximum leaf requests combined from all actors into one model forward pass.",
    )
    parser.add_argument(
        "--inference-wait-ms", type=float, default=1.0,
        help="Brief queue window for combining leaves from concurrent MCTS trees.",
    )
    args = parser.parse_args()
    training = training_config_from_args(args)
    device = select_device(training.device)
    model, model_config = load_model(args.model_in, device)
    frozen_models = [load_model(path, device)[0] for path in args.opponent_model]
    summary = train_self_play(
        training,
        model_config,
        mcts_config_from_args(args),
        games=args.games,
        updates_per_game=args.updates_per_game,
        opponent=args.opponent,
        random_opponent_rate=args.random_opponent_rate,
        mixed_opponent=args.mixed_opponent,
        teacher_replay_fraction=args.teacher_replay_fraction,
        workers=args.workers,
        global_inference_batch_size=args.global_inference_batch_size,
        inference_wait_ms=args.inference_wait_ms,
        model_out=args.model_out,
        model=model,
        opponent_models=frozen_models,
    )
    print_summary(summary)


if __name__ == "__main__":
    main()
