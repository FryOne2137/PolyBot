"""Stage 2: improve an existing belief model with in-memory MCTS self-play."""

from __future__ import annotations

import argparse
from pathlib import Path

from _bootstrap import add_local_source_root

add_local_source_root()

from polybot.infrastructure.device import select_device
from polybot.infrastructure.model_io import load_model
from polybot.training.cli import (
    add_environment_options,
    mcts_config_from_args,
    print_summary,
    training_config_from_args,
)
from polybot.training.self_play_train import train_self_play


def main() -> None:
    parser = argparse.ArgumentParser(description="Run RAM-only MCTS self-play; save only model weights")
    add_environment_options(parser)
    parser.add_argument("--model-in", type=Path, required=True)
    parser.add_argument("--model-out", type=Path, default=Path("models/self_play.pt"))
    parser.add_argument("--games", type=int, default=200)
    parser.add_argument("--updates-per-game", type=int, default=4)
    parser.add_argument("--batch-size", type=int, default=16)
    parser.add_argument("--exploration-rate", type=float, default=0.20)
    parser.add_argument("--priority-replay-fraction", type=float, default=0.35)
    parser.add_argument("--opponent", choices=["self_play", "random", "heuristic", "mixed"], default="self_play")
    parser.add_argument("--random-opponent-rate", type=float, default=0.50)
    parser.add_argument("--mixed-opponent", choices=["random", "heuristic"], default="heuristic")
    parser.add_argument(
        "--teacher-replay-fraction",
        type=float,
        default=0.25,
        help="Fraction of every optimisation batch regenerated by the heuristic teacher in RAM.",
    )
    parser.add_argument("--simulations", type=int, default=64)
    parser.add_argument("--particles", type=int, default=4)
    parser.add_argument("--inference-batch-size", type=int, default=8)
    parser.add_argument(
        "--actor-workers",
        type=int,
        default=1,
        help="Parallel CPU self-play actors sharing one CUDA inference worker.",
    )
    parser.add_argument(
        "--actor-round-games",
        type=int,
        default=8,
        help="Queued games per actor before pausing all actors for model updates.",
    )
    parser.add_argument("--inference-max-batch-size", type=int, default=64)
    parser.add_argument("--inference-wait-ms", type=float, default=0.25)
    args = parser.parse_args()
    training = training_config_from_args(args)
    model, model_config = load_model(args.model_in, select_device(training.device))
    summary = train_self_play(
        training,
        model_config,
        mcts_config_from_args(args),
        games=args.games,
        updates_per_game=args.updates_per_game,
        opponent=args.opponent,
        random_opponent_rate=args.random_opponent_rate,
        mixed_opponent=args.mixed_opponent,
        teacher_replay_fraction=args.teacher_replay_fraction,
        actor_workers=args.actor_workers,
        actor_round_games=args.actor_round_games,
        inference_max_batch_size=args.inference_max_batch_size,
        inference_wait_ms=args.inference_wait_ms,
        model_out=args.model_out,
        model=model,
    )
    print_summary(summary)


if __name__ == "__main__":
    main()
